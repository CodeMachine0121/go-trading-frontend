/**
 * Domain Model：要看的那一段裡，那個市場**根本沒有開過**時該對使用者說的那一句話。
 *
 * 它是第三種「算不出來」，而三種的差別不在嚴重程度，在**出路的方向**：
 *
 * - 湊不出最少可算根數 → 歷史不夠深，出路是讓每一格涵蓋短一點，或把缺的歷史補回來。
 * - 一次要得太多 → 出路是縮短要看的區間，或讓每一格涵蓋長一點。
 * - **這一種 → 上面四條路一條都沒有用。** 週六不會因為換了刻度就長出成交，
 *   把區間拉長也只是拉進更多沒有交易的時間。唯一的出路是改看市場有開的時候。
 *
 * 所以這句話**不得出現「刻度」，也不得出現「縮短」或「拉長」**。它們是另外兩句的動詞，
 * 共用一個，使用者就會照著去調一個調了也沒用的地方——而那些地方都調得動，
 * 於是他不會發現自己在原地打轉，只會覺得這個畫面壞了。
 *
 * 它也**不指名任何一個控制項**（哪一顆按鈕、哪一個選單），理由與另外兩句相同：
 * 同一句話會出現在圖表與指標計算兩個畫面上，而那兩個畫面的控制項不一樣。
 * 指名一個，就會在另一個畫面上叫使用者去按一個不存在的東西。
 */
export class MarketClosedThroughoutDomain {
  message(): string {
    return '這一段時間市場沒有交易，所以沒有東西可以算。'
      + '請改看這個市場有交易的時間——這一檔不是全天候交易的，'
      + '收盤之後與週末不會有任何成交。'
  }
}
