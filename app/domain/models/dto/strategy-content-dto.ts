/**
 * DTO：一支策略記著的兩樣東西——算式內容與指標值種類。
 *
 * **這兩樣只有這一種形狀。** 它同時是「載入時帶進畫面的東西」、「儲存時送出去的東西」、
 * 以及「拿來比對有沒有被改過的東西」。三處各自定義一份就有三份會漂移的複本，
 * 而「有沒有改過」一旦漏比一個欄位，使用者寫的東西就會被靜靜蓋掉。
 *
 * **不含交易標的、彙總刻度與計算根數**——那三樣描述的是**某一次執行**，不是這套算法。
 * 同一支策略要能在不同市場、不同粗細下反覆執行，它們因此跟著計算的請求走。
 * 它們留在這裡的代價很具體：載入一支策略會把使用者正在用的粗細換掉，
 * 而改一下刻度也會被算成「有東西還沒存」。
 *
 * 種類收的是字串而不是那組窄型別，因為這個形狀是雙向的：
 * 畫面上的選單天生交出字串，硬要窄型別就得在畫面上加一個編譯器檢查不了的斷言，
 * 那等於用一句「相信我」換來型別看起來很嚴謹。真正的把關在 domain——
 * 存進去時由 StrategyWriteDomain 正規化，交出來時 StrategyDomain 保證已經正規化過。
 */
export class StrategyContentDto {
  constructor(
    public readonly scriptBody: string,
    public readonly resultType: string,
  ) {}
}
