/**
 * 一個策略參數是哪一種。有限的兩種，所以是字面量聯合而不是自由字串。
 *
 * 分種類的第一個理由是**系統必須知道要拿多少 K 線**——那只有回看根數那一種算數。
 * 其餘的差別都在「怎麼讀它」：數值原樣交出去，是非零是否、非零是是。
 * 順帶讓畫面在使用者填任何值之前就長得出正確的格子，
 * 也讓「回看根數必須是大於零的整數」有地方成立。
 */
export type StrategyParameterKind = 'lookbackCount' | 'number' | 'boolean'

/**
 * 可以宣告的每一種，**一份清單**。
 *
 * 它存在的理由是：問「是不是回看根數」的地方加一種種類不會壞，
 * **列舉全部種類的地方會**。系統那一側早就把它們收在一份清單裡；
 * 這一側曾經沒有，於是新增「是非」的時候，把後端回來的種類收乾淨的那一處漏掉了——
 * 存好的是非讀回來變成數值，沒有任何地方報錯。
 */
export const STRATEGY_PARAMETER_KINDS: readonly StrategyParameterKind[] = [
  'lookbackCount',
  'number',
  'boolean',
]

/**
 * DTO：一個策略參數的唯一形狀。
 *
 * **它是雙向的**：載入策略時帶進畫面的是它，存起來時送出去的是它，
 * 拿來比對「有沒有被改過」的也是它。
 *
 * **值只有一個欄位，型別具體。** 這裡沒有三種型別可以裝——使用者交出來的是一個數字，
 * 不同的是系統怎麼讀它。是非也是一個數字（零是否、非零是是），
 * 所以多一種讀法完全不必動到值是怎麼存、怎麼送的。回看根數是整數，而整數在這個型別裡精確到 2^53，
 * 遠大於它會用到的範圍；「它是整數」由 kind 保證，所以驗證那一側必須真的檢查，
 * 不能假設。
 *
 * **`value` 的意思隨它所在的地方而不同，這是刻意的：**
 * 在**指標計算畫面**上它既是這一次要用的值，也是存起來之後的預設值——
 * 寫算式的時候，試一個值與定一個預設值本來就是同一件事。
 * 在 **K 線圖表**上它只是**這一次套用**的值：那裡套用的是一支已經定案的策略，
 * 改動它的預設值等於在使用者沒察覺的情況下改掉他的策略。
 * 一支策略讀進來時它帶的是預設值，兩邊都從那裡出發。
 */
export class StrategyParameterDto {
  constructor(
    public readonly name: string,
    public readonly kind: StrategyParameterKind,
    public readonly value: number,
  ) {}
}
