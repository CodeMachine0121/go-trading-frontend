/**
 * VO：留存下來的**一筆套用**——哪一支策略，以及那幾格被調成什麼。
 *
 * **它不是「圖上那一筆」的快照，是「使用者當時要求了什麼」。**
 * 還原時真相在策略清單那一側：那支策略可能已經被刪、被改名、改了宣告、
 * 或者現在畫不成線了。這裡只提供「他要哪一支、各配什麼值」。
 *
 * **種類刻意不在裡面。** 種類是宣告說的——留存它只會讓一份過期的種類贏過宣告，
 * 而那件事不會報錯：存好的是非讀回來變成數值，畫面照樣長得出格子。
 * 後端在「策略讀回來時參數的種類」上踩過同一個坑。
 *
 * **值用 `Map` 而不是第二個 VO**：還原時對它做的唯一一件事就是「按名稱查」，
 * 而那正是 `Map` 的形狀。
 */
export class RememberedAppliedIndicatorVo {
  constructor(
    public readonly strategyId: number,
    /** 名稱 → 那一次調成的值。留存裡沒有那個名字時，還原會用宣告的預設值。 */
    public readonly parameterValues: ReadonlyMap<string, number>,
  ) {}
}
