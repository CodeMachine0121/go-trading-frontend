/**
 * VO：一次計算要為**哪一段行情**拿到值。不可變、無行為。
 *
 * 它取代了原本送出去的「幾格」。那個數字要由「這一段有多長」除以「每根涵蓋多久」
 * 算出來，而那條算式預設那段時間裡的每一分鐘市場都在成交——會收盤的市場不是這樣，
 * 於是畫面要了五倍的格子，而線悄悄地用上了好幾個交易日的行情。
 * 一段裡有幾格取決於那個市場的作息，作息是系統知道的事，所以畫面說的是這一段本身。
 *
 * **兩端住在一起**，因為它們本來就是同一段的兩端：分成兩個欄位搬運，就有機會只搬走一半。
 *
 * 產生它的方式一律是來源身上的 `toObservationWindow()`——圖表那一段自己知道自己從哪裡
 * 到哪裡，指標計算畫面的「要看多長」自己知道要往回推多久。寫成這裡的一個工廠，
 * 就得把別人的資料整包搬進來。
 */
export class ObservationWindowVo {
  constructor(
    public readonly startTime: Date,
    /**
     * 這一段的終點，也就是算到哪一刻。
     *
     * **`null` 是一個答案而不是缺值**：它的意思是「算到現在」，而系統本來就規定
     * 未指定即視為現在。整條路上只有來源產生它、只有 proxy 消費它。
     */
    public readonly endTime: Date | null,
  ) {}
}
