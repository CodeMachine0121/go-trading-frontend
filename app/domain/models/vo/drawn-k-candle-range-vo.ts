/**
 * VO：圖上實際畫出來的那一段——從第幾根畫到第幾根。不可變、無行為。
 *
 * **序位不是時刻**，而這正是它存在的理由。使用者要看的那一段說得出兩個時刻
 * （見 `ChartVisibleRangeVo`），但**最新那一根右邊那段還沒發生的空白說不出時刻**——
 * 那裡沒有 K 線，也就沒有時間指得到它。以序位表達就成立了：
 * 只有二百八十八根的圖上，「畫到第三百根」是一句合法的話，多出來的十二根寬度就是留白。
 *
 * 因此 `to` **允許超過最後一根**，也允許是小數（留白是根數的一成，本來就不會是整數）。
 * 超出的那一段就是右側留白。
 *
 * 兩個數字合成一個物件，是因為它們**只有成對才有意義**，而且要一起穿過
 * DTO、prop、繪圖函式庫三層。拆成兩個數字傳，每一層都得自己記住
 * 「右邊那個可能超過最後一根」——那句話遲早會在某一層被忘記。
 */
export class DrawnKCandleRangeVo {
  constructor(
    public readonly from: number,
    public readonly to: number,
  ) {}
}
