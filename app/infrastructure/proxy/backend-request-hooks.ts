/**
 * 發請求的那一層在三個時刻要呼叫的應用程式編排：被登出、救回這一段登入、開始等一件事。
 *
 * 它們收成一份而不是三個各自排隊的建構子參數：每一個打後端的 proxy 都拿到**同一份**，
 * 由組裝根建一次；多一個時刻時只改這裡與組裝根，不必把十幾個 proxy 的建構子各改一遍。
 *
 * 三個都是回呼而不是介面，理由與它們各自的說明相同：那不是一份資料，也不是一個外部資源，
 * 而是應用程式的編排——發請求的東西不該懂得導頁、不該擁有「現在是誰在用」，也不該認識畫面。
 * 每一個都有什麼都不做的預設，所以只在乎請求本身的測試一個都不必給。
 */
export class BackendRequestHooks {
  constructor(
    /**
     * 被登出時要做的事——通常是清掉全站共用的那份狀態並回到登入畫面。
     */
    readonly onSignedOut: () => void = () => {},
    /**
     * 試著把這一段登入救回來，救回來了回 `true`。
     *
     * 它存在是因為**登入憑證只活十五分鐘，而續用憑證活三十天**。少了它，坐在圖表前
     * 十六分鐘之後按一下計算，就會被踢回登入畫面——而手上那份續用憑證明明還好著。
     *
     * 它必須**同時只跑一次**（這件事由給進來的那一邊保證）：續用憑證用過就失效，
     * 同時換兩次會被後端判定為盜用，把「這台需要重登」升級成「這個人每一台都被登出」。
     */
    readonly recoverSession: () => Promise<boolean> = async () => false,
    /**
     * 開始等一件事，回傳「這一件結束了」——頂端那條進度條就是從這裡知道畫面在等的。
     *
     * 報到由發請求的那一層統一做，而不是每一個呼叫端：只要有一條路忘了報到，
     * 就是一個按下去之後畫面看起來什麼都沒發生的洞。
     */
    readonly beginWaiting: () => () => void = () => () => {},
  ) {}
}
